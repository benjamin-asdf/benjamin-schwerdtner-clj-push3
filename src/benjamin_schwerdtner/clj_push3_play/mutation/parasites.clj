(ns benjamin-schwerdtner.clj-push3-play.mutation.parasites
  "Host-parasite coevolution for [[benjamin-schwerdtner.clj-push3-play.mutation.dual]].

  Why this exists, in one line: to make copying unprofitable rather than
  illegal.

  Once M can read the population (:code_other), the cheapest way to score well
  is to hand back the fittest genome you can find. That is not variation, it
  is transcription, and it earns credit under any 'did the child beat its
  parent' measure. The hand-written fix is to forbid it. The parasite
  hypothesis is the other fix and it is better: a genotype that takes over
  becomes a large uniform target, parasites adapt to it, and its fitness
  collapses. Nothing is forbidden - copying is simply a bad bet.

  The same mechanism is aimed at two other things we measured and could not
  fix from inside a stationary landscape:

  - THE PLATEAU. Selection on M rewards inducing improvement, so every
    improvement M finds shrinks the supply of improvements left. `improvements`
    went 120 -> 0 in the asexual runs. Coevolution regenerates the supply,
    because what you are measured against evolves too.
  - THE CONTROL THAT COULD NOT DISCRIMINATE. Evolvability buys nothing on a
    fixed landscape, which is why evolved M did not beat frozen M on the
    busy-beaver toy. Barnett/Meister/Rainey got selection for evolvability out
    of an environment that kept changing.

  ------------------------------------------------------------------------
  What a parasite is here
  ------------------------------------------------------------------------

  Busy beaver has no attack surface - you cannot parasitize a scalar. Symbolic
  regression does: a parasite is a TEST POINT, and it is fit when hosts fail
  on it (Hillis 1990, coevolved sorting networks against test inputs).

  That makes host fitness frequency-dependent without anyone writing a
  frequency term: parasites concentrate on whatever the current hosts cannot
  do, so a host strategy that becomes common becomes the thing parasites are
  selected to defeat.

  It is also, structurally, `aspects of play` from ideas/BIG_IDEAS.org - the
  parasite population IS the set of contexts, and it is generated by the
  process instead of supplied by a designer. That document asks 'what are the
  fitness contexts? It is an open ended problem creative itself'. This is one
  answer to where they come from.

  ------------------------------------------------------------------------
  Known failure modes, not hidden
  ------------------------------------------------------------------------

  Host-parasite coevolution is unstable in well-documented ways (Ficici and
  Pollack, cited in BIG_IDEAS.org): cycling, DISENGAGEMENT where one side wins
  so completely that the gradient vanishes, and mediocre stable states. The
  mitigations here are deliberately minimal - an archive of hard cases, and a
  held-out objective benchmark that never enters selection so that progress
  can be distinguished from the opponents getting easier. If the benchmark is
  flat while host fitness climbs, the coevolution has disengaged and the run
  means nothing."
  (:require
   [benjamin-schwerdtner.clj-push3-play.interpreter :as push]
   [benjamin-schwerdtner.clj-push3-play.generator :as gen]
   [random-seed.core :as rs :refer [rand rand-int rand-nth]])
  (:refer-clojure :exclude [rand rand-int rand-nth]))

;; ---------------------------------------------------------------------------
;; The host: a program from x to y
;; ---------------------------------------------------------------------------

(def alphabet
  ;; Float literals, not integers: a literal goes to the stack of its own
  ;; type, so `1` would land on INTEGER and be invisible to every operator
  ;; here. x arrives on FLOAT and the answer is read off FLOAT.
  [:float_+ :float_- :float_* :float_dup :float_swap
   :float_sin :float_cos
   1.0 2.0 3.0])

(def atom-generators (gen/identifier-generators alphabet))

(defn random-host
  ([] (random-host 12))
  ([max-points]
   (gen/generate-code {:max-points max-points
                       :atom-generators atom-generators
                       :branch-probability (constantly 0.1)
                       :close-probability (fn [n] (/ (- 1 (/ 1 n)) 3))})))

(defn run-host
  "y for a given x, or nil if the program named nothing."
  [program x]
  (try
    (let [st (push/execute (-> (push/setup-state)
                               (assoc :exceptions-are-warnings? true)
                               (update-in [:stacks :push/float] conj (double x)))
                           program
                           {:max-executions 200})
          stack (-> st :stacks :push/float)]
      (when (seq stack)
        (let [v (double (peek stack))]
          (when (and (not (Double/isNaN v)) (not (Double/isInfinite v)))
            v))))
    (catch Throwable _ nil)))

(defn error
  "How badly `program` does at `x`. Unbounded failure is capped so that one
  catastrophic point cannot dominate a whole error sum."
  [target program x]
  (let [y (run-host program x)]
    (if (nil? y)
      1.0
      (min 1.0 (/ (Math/abs (- y (target x)))
                  (+ 1.0 (Math/abs (double (target x)))))))))

;; ---------------------------------------------------------------------------
;; The parasite population
;; ---------------------------------------------------------------------------
;;
;; A parasite is just a number - the point it attacks. Kept deliberately dumb:
;; the interesting evolution is supposed to be in M, and a parasite with its
;; own program would add a third search problem to debug at the same time.

(defn random-parasite [lo hi] (+ lo (* (rand) (- hi lo))))

(defn parasite-fitness
  "A parasite is fit when hosts fail on it - mean host error at its point."
  [target hosts x]
  (let [n (count hosts)]
    (if (zero? n)
      0.0
      (/ (reduce + 0.0 (map #(error target % x) hosts)) n))))

(defn step-parasites
  "One generation of parasites: keep the ones hosts fail on, replace the rest.

  Survivors are the hard cases, so this doubles as the archive that keeps
  coevolution from cycling straight back to points the hosts already solved."
  ;; `parasites` first: this is called through swap!, which hands the atom's
  ;; value in as the first argument.
  [parasites {:keys [target lo hi n-parasites keep-frac]} hosts]
  (let [scored (sort-by #(parasite-fitness target hosts %) > parasites)
        keep-n (max 1 (long (* keep-frac n-parasites)))
        survivors (vec (take keep-n scored))]
    (into survivors
          (repeatedly (- n-parasites keep-n) #(random-parasite lo hi)))))

;; ---------------------------------------------------------------------------
;; Wiring it into the dual loop
;; ---------------------------------------------------------------------------

(def defaults
  {:target (fn [x] (+ (* x x x) (* x x) x))
   :lo -2.0
   :hi 2.0
   :n-parasites 24
   :keep-frac 0.5
   ;; The held-out yardstick. Fixed, never enters selection, only reported.
   :benchmark-points (mapv #(+ -2.0 (* 0.2 %)) (range 21))})

(defn make
  "Returns the pieces [[dual/run]] needs for a coevolutionary run.

  `:fitness` scores a host against the CURRENT parasites, so it moves; that is
  why `:stationary-fitness?` has to be false and the loop drops its cache each
  generation. `:benchmark` scores against a fixed grid and is reported only."
  [opts]
  (let [{:as cfg :keys [target lo hi n-parasites benchmark-points seed]}
        (merge defaults opts)
        ;; Seeded explicitly. `*rng*` at the root is a single mutable
        ;; java.util.Random, so drawing here without a binding gives every
        ;; call in a JVM a different starting set - two runs of the "same"
        ;; configuration would not be comparable, which is fatal for a sweep.
        parasites (atom (binding [rs/*rng* (rs/random (long (or seed 0)))]
                          (vec (repeatedly n-parasites #(random-parasite lo hi)))))
        ;; Hosts as of the last generation - what the parasites are scored
        ;; against. Read from the loop state so the parasites chase the actual
        ;; population rather than a fixed sample.
        hosts (atom [])]
    {:parasites parasites
     :config
     {:random-genome random-host
      :alphabet alphabet
      :stationary-fitness? false
      ;; Lower is better here, so the comparator is inverted.
      :better? (fn [a b] (neg? (compare a b)))

      :fitness
      (fn [program]
        (let [ps @parasites
              n (count ps)]
          (if (zero? n)
            1.0
            (/ (reduce + 0.0 (map #(error target program %) ps)) n))))

      :benchmark
      (fn [program]
        (/ (reduce + 0.0 (map #(error target program %) benchmark-points))
           (count benchmark-points)))

      :before-generation
      (fn [state]
        (let [current (mapv :program (:e state))]
          (reset! hosts current)
          ;; Parasites move first, then hosts are scored against them. The
          ;; order is the Red Queen: you are always being measured by an
          ;; opponent that has already seen what you did last generation.
          (swap! parasites step-parasites cfg current)))}}))

